    );
  }

  /// If non-null, the style to use for this text.
  ///
  /// If the style's "inherit" property is true, the style will be merged with
  /// the closest enclosing [DefaultTextStyle]. Otherwise, the style will
  /// replace the closest enclosing [DefaultTextStyle].
  final TextStyle? styleOverridden;

  /// Collected text style from shortcuts
  TextStyle get styleFromShortcuts => TextStyle(
        color: color,
        backgroundColor: backgroundColor,
        shadows: shadows,
        fontFamily: fontFamily,
        fontSize: fontSize,
        fontWeight: fontWeight,
        fontStyle: fontStyle,
        letterSpacing: letterSpacing,
        wordSpacing: wordSpacing,
        textBaseline: textBaseline,
        height: height,
      );

  bool get _hasShortcuts =>
      color != null ||
      backgroundColor != null ||
      shadows != null ||
      fontFamily != null ||
      fontSize != null ||
      fontWeight != null ||
      fontStyle != null ||
      letterSpacing != null ||
      wordSpacing != null ||
      textBaseline != null ||
      height != null;

  @override
  Widget build(BuildContext context) {
    final variantStyle = variant?.call(context);
    TextStyle? effectiveStyle =
        variantStyle?.merge(styleOverridden) ?? styleOverridden;
    if (_hasShortcuts) {
      effectiveStyle =
          effectiveStyle?.merge(styleFromShortcuts) ?? styleFromShortcuts;
    }

    if (effectiveStyle != null) {
      return DefaultTextStyle.merge(
        style: effectiveStyle,
        child: Builder(builder: (context) => super.build(context)),
      );
    }
    return super.build(context);
  }

